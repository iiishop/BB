"""Generate Dart wire DTOs/typed calls from the sole exported Space contract."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
actions = json.loads((root / 'server/contract/space-v1.json').read_text())['actions']
def camel(s):
    a, *b = s.split('_')
    return a + ''.join(v.title() for v in b)
def name(s):
    # ProfileMonth is the wire coordinate; the UI already owns a richer
    # SpaceProfileMonth value object (label/sort/equality), so the generated
    # DTO gets a distinct name instead of colliding with it.
    if s == 'ProfileMonth':
        return 'SpaceMonthCoordinate'
    return 'Space' + s.replace('[', '').replace(']', '').replace('_', '')
def nullable(s):
    return 'anyOf' in s and any(x.get('type') == 'null' for x in s['anyOf'])
def inner(s):
    return next(x for x in s['anyOf'] if x.get('type') != 'null') if nullable(s) else s
def dtype(s):
    if nullable(s): return dtype(inner(s)) + '?'
    if '$ref' in s: return name(s['$ref'].split('/')[-1])
    t=s.get('type')
    if t=='array': return 'List<' + dtype(s['items']) + '>'
    return {'string':'String','integer':'int','boolean':'bool'}[t]
def decode(s, expr):
    if nullable(s): return f'{expr} == null ? null : {decode(inner(s),expr)}'
    if '$ref' in s: return f'{dtype(s)}.fromJson({expr} as Map<String, dynamic>)'
    if s.get('type')=='array': return f'({expr} as List).map((v) => {decode(s["items"],"v")}).toList()'
    return f'{expr} as {dtype(s)}'
def encode(s, expr):
    if nullable(s):
        base = inner(s)
        if '$ref' in base: return expr+'?.toJson()'
        return expr
    if '$ref' in s: return expr+'.toJson()'
    if s.get('type')=='array': return expr+'.map((v) => '+encode(s['items'],'v')+').toList()'
    return expr
models={}
for a in actions.values():
    for kind in ['request','response']:
        s=a[kind]
        models.update(s.get('$defs',{}))
        if kind=='response': models[s['title']]=s
out=['// GENERATED by client/tool/generate_space.py. Do not edit.\n']
for key,s in models.items():
    n=name(key); props=s['properties']
    out += [f'class {n} {{', f'  const {n}({{'+', '.join('required this.'+camel(k) for k in props)+'});']
    out += [f'  final {dtype(v)} {camel(k)};' for k,v in props.items()]
    out += [f'  factory {n}.fromJson(Map<String, dynamic> json) => {n}(']
    out += [f"    {camel(k)}: {decode(v, 'json['+repr(k)+']')}," for k,v in props.items()]
    out += ['  );','  Map<String, dynamic> toJson() => {']
    out += [f"    '{k}': {encode(v,camel(k))}," for k,v in props.items()]
    out += ['  };','}\n']
(root/'client/lib/models/space_models.dart').write_text('\n'.join(out))
# Keep validators tied to the exported schema, including nested identity/ack DTOs.
def compact(v):
    if isinstance(v,dict): return {k:compact(x) for k,x in v.items() if k not in ('title','description')}
    if isinstance(v,list): return [compact(x) for x in v]
    return v
schemas={k:{t:compact(v[t]) for t in ['request','response','local_request']} for k,v in actions.items()}
(root/'client/lib/services/space_schema.g.dart').write_text("// GENERATED by client/tool/generate_space.py.\nimport 'dart:convert';\nfinal Map<String, dynamic> spaceSchemas = jsonDecode(r'''"+json.dumps(schemas,separators=(',',':'))+"''') as Map<String, dynamic>;\n")
out=['// GENERATED by client/tool/generate_space.py.\n',"import 'client_identity.dart';", "import 'space_api_client.dart';", "import 'space_service.dart';",'']
# Both transports implement one typed request boundary; UI uses SpaceService.
for cls in ['SpaceApiClient','SpaceService']:
    out += [f'extension {cls}Methods on {cls} {{']
    for action,a in actions.items():
        s=a['request']; n=name(a['response']['title']); params=[]
        if cls=='SpaceApiClient': params.append('required String token')
        else: params.append('ExpectedIdentity? expectedIdentity')
        for k,v in s['properties'].items():
            typ=dtype(v)
            if k in s.get('required',[]): decl='required '+typ+' '+camel(k)
            else:
                default=v.get('default')
                if default is None: decl=typ+' '+camel(k)
                else: decl=typ+' '+camel(k)+' = '+json.dumps(default)
            params.append(decl)
        out += [f'  Future<{n}> {camel(action)}({{'+', '.join(params)+'}) async {',f"    final body = await call('{action}', {{"]
        out += [f"      '{k}': {encode(v,camel(k))}," for k,v in s['properties'].items()]
        out += ['    }, '+('token: token' if cls=='SpaceApiClient' else 'expectedIdentity: expectedIdentity')+');',f'    return {n}.fromJson(body);','  }']
    out += ['}']
(root/'client/lib/services/space_methods.g.dart').write_text('\n'.join(out)+'\n')
